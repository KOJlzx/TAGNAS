def configure_hf_runtime(*, local_files_only: bool) -> None:
    """Configure HuggingFace online/offline environment variables.

    This must run before importing transformers in any worker process.
    """
    if local_files_only:
        os.environ["TRANSFORMERS_OFFLINE"] = "1"
        os.environ["HF_DATASETS_OFFLINE"] = "1"
        os.environ["HF_HUB_OFFLINE"] = "1"
        return

    os.environ["TRANSFORMERS_OFFLINE"] = "0"
    os.environ["HF_DATASETS_OFFLINE"] = "0"
    os.environ["HF_HUB_OFFLINE"] = "0"


def prefetch_hf_assets(config_path: str, *, local_files_only: bool) -> None:
    """Prewarm tokenizer and LM weights in the parent process.

    This fails fast when assets are missing or downloads fail, avoids several
    spawned workers attempting first-time downloads concurrently, and lets child
    processes read the already-populated HuggingFace cache.
    """
    loaded = OmegaConf.to_container(OmegaConf.load(config_path), resolve=True)
    assert isinstance(loaded, dict)

    data_args = dict(loaded["data"]["init_args"])
    model_args = dict(loaded["model"]["init_args"])
    tokenizer_name = str(data_args["tokenizer_name"])
    lm_name = str(model_args["lm_name"])

    import transformers as tf

    kwargs = {"local_files_only": local_files_only}
    try:
        print(
            "[async-train] prefetch_hf_assets "
            f"tokenizer={tokenizer_name} lm={lm_name} local_only={local_files_only}"
        )
        tf.AutoTokenizer.from_pretrained(tokenizer_name, **kwargs)
        tf.AutoModel.from_pretrained(lm_name, **kwargs)
    except Exception as exc:
        mode = "offline-only" if local_files_only else "online-enabled"
        raise RuntimeError(
            "Failed to prepare Hugging Face assets before spawning workers. "
            f"mode={mode} tokenizer={tokenizer_name} lm={lm_name}"
        ) from exc


def seed_everything(seed: int) -> None:
    """Seed all random number generators used by this runtime."""
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)


