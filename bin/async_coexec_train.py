def dump_cli_args(config: AsyncTrainConfig, args: argparse.Namespace) -> None:
    """Persist CLI arguments for reproducibility.

    Writes both a structured JSON file and a shell script that can replay the
    command line used for this run.
    """
    output_dir = config.train_output_dir
    output_dir.mkdir(parents=True, exist_ok=True)

    def _json_default(obj):  # Fallback for Path and other non-native JSON values.
        if isinstance(obj, Path):
            return str(obj)
        return str(obj)

    with (output_dir / "cli_args.json").open("w", encoding="utf-8") as handle:
        json.dump(vars(args), handle, indent=2, default=_json_default)

    # Reproducible shell command: record Python executable and original argv with shlex escaping.
    command_line = " ".join(shlex.quote(piece) for piece in [sys.executable, *sys.argv])
    with (output_dir / "cli_args.sh").open("w", encoding="utf-8") as handle:
        handle.write("#!/usr/bin/env bash\n")
        handle.write(f"# Auto-generated at {datetime.now().isoformat()}\n")
        handle.write(f"# stage={config.stage}  run_name={config.run_name}\n")
        handle.write(f"cd {shlex.quote(str(Path.cwd()))}\n")
        handle.write(command_line + "\n")


def run_stage(config: AsyncTrainConfig, args: argparse.Namespace | None = None) -> None:
    """Run one training stage, either search or retrain.

    mp.spawn launches config.world_size child processes. Each process executes
    worker_main(rank, config), and join=True blocks the parent until all children exit.
    """
    if args is not None:
        dump_cli_args(config, args)
    print(
        f"[async-train] stage={config.stage} "
        f"run_dir={config.train_output_dir.parent} output_dir={config.train_output_dir}"
    )
    mp.spawn(worker_main, nprocs=config.world_size, args=(config,), join=True)


def build_run_name() -> str:
    """Generate a unique run name for output-directory isolation."""
    timestamp = datetime.now().strftime("%Y%m%d-%H%M%S")
    return f"run-{timestamp}-pid{os.getpid()}"


def main() -> None:
    """Program entry point.

    Execution order:
    1. Parse CLI arguments.
    2. Configure HuggingFace online/offline behavior.
    3. Prewarm tokenizer and LM assets in the parent process.
    4. Run search, retrain, or search-then-retrain depending on --phase.
    """
    args = parse_args()
    configure_hf_runtime(local_files_only=args.offline_models_only)
    # Prewarm in the parent process so model download failures surface before spawning workers.
    prefetch_hf_assets(args.config_path, local_files_only=args.offline_models_only)
    run_name = build_run_name()

    if args.phase == "both":
        # Run search first, then retrain.
        search_config = build_stage_config(
            args,
            stage="search",
            dist_port=args.dist_port,
            rpc_port=args.rpc_port,
            run_name=run_name,
            genotype_path=None,  # The search stage writes its own genotype.
        )
        run_stage(search_config, args=args)

        # The retrain stage consumes the genotype produced by search. Ports are
        # offset to avoid conflicts with any still-tearing-down resources. When
        # warm start is enabled, pass search-stage graph/text checkpoints through.
        warm_graph = _pick_warm_ckpt(
            search_config.graph_best_ckpt_path,
            search_config.graph_ckpt_path,
        ) if args.retrain_warm_start else None
        warm_text = _pick_warm_ckpt(
            search_config.text_best_ckpt_path,
            search_config.text_ckpt_path,
        ) if args.retrain_warm_start else None

        retrain_config = build_stage_config(
            args,
            stage="retrain",
            dist_port=args.dist_port + 10,
            rpc_port=args.rpc_port + 10,
            run_name=run_name,
            genotype_path=str(search_config.genotype_file_path),
            warm_start_graph_ckpt=warm_graph,
            warm_start_text_ckpt=warm_text,
        )
        run_stage(retrain_config, args=args)
        return

    # Single-stage execution.
    if args.phase == "retrain" and args.genotype_path is None:
        raise ValueError("--genotype-path is required for --phase retrain")

    stage_config = build_stage_config(
        args,
        stage=args.phase,
        dist_port=args.dist_port,
        rpc_port=args.rpc_port,
        run_name=run_name,
        genotype_path=args.genotype_path,
        warm_start_graph_ckpt=args.warm_start_graph_ckpt,
        warm_start_text_ckpt=args.warm_start_text_ckpt,
    )
    run_stage(stage_config, args=args)


if __name__ == "__main__":
    main()
