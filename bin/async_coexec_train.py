# Part 5: child-process entry point
# ======================================================================

def worker_main(rank: int, config: AsyncTrainConfig) -> None:
    """Entry point called by mp.spawn for each rank.

    Flow:
    1. Resolve the role name for this rank.
    2. Bind text workers to their assigned GPU.
    3. Initialize the global Gloo process group for rendezvous.
    4. Initialize the text-side process group for text-worker synchronization.
    5. Build and install the role-specific service object.
    6. Initialize TensorPipe RPC for cross-process calls.
    7. Dispatch to coordinator control loop or worker training loop.
    8. Shut down RPC and destroy process groups in finally.
    """
    role_name = config.role_for_rank(rank)
    # Optional rank-local logging. When ASYNC_WORKER_LOG_DIR is set, each worker
    # writes stdout/stderr and exception tracebacks to an independent file.
    import os, sys, traceback
    _log_dir = os.environ.get("ASYNC_WORKER_LOG_DIR")
    if _log_dir:
        os.makedirs(_log_dir, exist_ok=True)
        _log_fh = open(os.path.join(_log_dir, f"rank{rank}-{role_name}.log"), "w", buffering=1)
        sys.stdout = _log_fh
        sys.stderr = _log_fh
        print(f"[rank{rank}] role={role_name} pid={os.getpid()} starting", flush=True)
    seed_everything(config.seed)

    # Text workers must bind their CUDA device explicitly; otherwise CUDA uses the default device.
    if role_name.startswith("text_worker_"):
        device = config.text_device(config.text_worker_index(role_name))
        if device.startswith("cuda"):
            torch.cuda.set_device(config.text_worker_index(role_name))
            # Create the CUDA context now, before the (tens of seconds of) data loading: on a shared
            # machine with Exclusive_Process cards, a card that is free when the run starts can be
            # taken by someone else's job in that window, and the run then dies with "CUDA-capable
            # device(s) is/are busy or unavailable" long after launch.
            torch.zeros(1, device=f"cuda:{config.text_worker_index(role_name)}")

    rpc_started = False
    try:
        # Step 1: initialize the global process group. Gloo is CPU-oriented and
        # is used here for rendezvous plus text-worker all_reduce synchronization.
        dist.init_process_group(
            backend="gloo",
            init_method=config.dist_init_method,  # Example: tcp://127.0.0.1:29590
            rank=rank,
            world_size=config.world_size,
        )

        # Step 2: initialize the text-side process group.
        text_group = init_text_group(config)

        # Step 3: build the service implementation for this role.
        # coordinator → CoordinatorTrainingService
        # graph_worker → GraphWorkerTrainingService
        # text_worker_N → TextWorkerTrainingService
        service = build_training_service_for_role(config=config, role_name=role_name, text_group=text_group)
        # Install the service globally so RPC handlers can resolve it through get_service().
        install_service(service)
        # Convert Ctrl+C / kill into a graceful runtime shutdown request.
        install_signal_handlers(service)

        # Step 4: initialize RPC. TensorPipe supports efficient local transports,
        # including shared-memory paths when available.
        backend_options = rpc.TensorPipeRpcBackendOptions(
            init_method=config.rpc_init_method,    # Example: tcp://127.0.0.1:29591
            rpc_timeout=config.rpc_timeout_seconds,
            num_worker_threads=32,
        )
        rpc.init_rpc(
            name=role_name,
            rank=rank,
            world_size=config.world_size,
            rpc_backend_options=backend_options,
        )
        rpc_started = True

        # Step 5: dispatch by role.
        if role_name == config.coordinator_name:
            # The coordinator waits for workers, broadcasts start, periodically
            # checks stop conditions, writes metrics, saves checkpoints, and exits
            # after every worker has completed.
            service.run_training()
        else:
            # Worker flow:
            # 1. Report readiness to the coordinator.
            rpc.rpc_sync(config.coordinator_name, _rpc_mark_worker_ready, args=(role_name,))
            # 2. Block until the coordinator broadcasts the start signal.
            service.wait_until_start()
            # 3. Enter the training loop. After local epochs finish, workers keep
            #    forward+push service alive until coordinator shutdown.
            service.run_training_loop()

    except BaseException:
        # Preserve the real traceback in the rank-local log before mp.spawn/RPC teardown.
        if _log_dir:
            traceback.print_exc(file=_log_fh)
            _log_fh.flush()
        raise
    finally:
        # Cleanup order matters: shut down RPC before destroying process groups.
        if rpc_started:
            with contextlib.suppress(Exception):
                rpc.shutdown(graceful=True)
        with contextlib.suppress(Exception):
            dist.destroy_process_group()


