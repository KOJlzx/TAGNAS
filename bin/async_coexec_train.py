#!/usr/bin/env python3
"""
Asynchronous distributed training entry point for GraphNAS + LM contrastive
learning on text-attributed graphs.

Architecture:
    This script launches a local multi-process job with a coordinator, one graph
    worker, and one or more text workers. Every process installs the service
    implementation for its role, then communicates through PyTorch RPC.

Process topology:
    rank 0  -> coordinator    (control plane: cache routing, metrics, checkpoints, shutdown)
    rank 1  -> graph_worker   (graph tower training and graph embedding pushes, usually on CPU)
    rank 2+ -> text_workers   (LM tower training and text embedding pushes, usually on GPUs)

Startup flow:
    1. The parent process parses CLI arguments.
    2. The parent process prewarms HuggingFace tokenizer/model assets to avoid
       concurrent downloads in child processes.
    3. mp.spawn starts all child processes.
    4. Each child initializes the distributed process group and RPC.
    5. The coordinator waits for worker readiness and broadcasts the start signal.
    6. Workers enter their role-specific training loops.
    7. The coordinator broadcasts shutdown after the stopping condition is met.

Training semantics:
    - Fully asynchronous optimistic execution: graph and text sides advance independently.
    - Drop-on-miss: a worker skips the update when peer embeddings are unavailable.
    - Workers push fresh embeddings even on misses, keeping caches warm.
    - Fixed-epoch workers report completion but continue forward+push service until all
      workers have finished, preventing one side from starving the other side's cache.
"""

