# Part 4: per-process initialization helpers
# ======================================================================

def init_text_group(config: AsyncTrainConfig) -> dist.ProcessGroup | None:
    """Create the text-worker ProcessGroup used for gradient synchronization.

    Only text workers participate in this group. The coordinator and graph worker
    receive None. When text synchronization is disabled or only one text worker is
    active, no group is needed.
    """
    if not config.text_sync_enabled:
        return None
    # Include only text worker ranks in this group.
    group = dist.new_group(ranks=config.text_worker_ranks, backend=config.text_sync_backend())
    if group == dist.GroupMember.NON_GROUP_MEMBER:
        # The current process is not a text worker and does not belong to this group.
        return None
    return group


def install_signal_handlers(service) -> None:
    """Install SIGINT/SIGTERM handlers for the current process.

    Signals request a graceful service shutdown instead of exiting immediately,
    allowing the training loop to stop at the next batch boundary.
    """
    def _handle_signal(signum, frame) -> None:
        del signum, frame
        service.request_shutdown()

    for signum in (signal.SIGINT, signal.SIGTERM):
        with contextlib.suppress(ValueError):
            signal.signal(signum, _handle_signal)


